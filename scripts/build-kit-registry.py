#!/usr/bin/env python3
"""Generate KIT-REGISTRY.md, the kit's function registry, from its docstrings.

WHY (SMADPickleBot #971, Gene 11/5/26 1:35 AM PT: "see why we aren't using Chuang Kit enough? Perhaps it needs a
registry/manifest, and every new feature or bug ticket work starts with looking at shared kit"). A host's own registry
lists its own code; nothing listed the kit's, so a session built a third copy of something the kit already had (a
Gmail watch, #969). This file is that list: read it before writing anything a second project could use.

WHAT. One section per module under src/chuang_platform_kit/: its first sentence, then every public top-level function
(signature, first paragraph of its docstring) and every public class with its public methods. A public name with no
docstring renders as `(no docstring)`, and tests/test-kit-registry.py fails on it and on a stale file.

USAGE.
    python scripts/build-kit-registry.py            # rewrite KIT-REGISTRY.md
    python scripts/build-kit-registry.py --check    # exit 1 if KIT-REGISTRY.md is stale
    python scripts/build-kit-registry.py --stdout   # print, write nothing
"""
import ast
import glob
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
PKG = os.path.join(ROOT, 'src', 'chuang_platform_kit')
OUT = os.path.join(ROOT, 'KIT-REGISTRY.md')
SUMMARY_CHARS = 260
NO_DOC = '(no docstring)'


def first_paragraph(doc):
    """The docstring's first paragraph, one line, cut to SUMMARY_CHARS; NO_DOC when there is none."""
    if not doc:
        return NO_DOC
    para = re.sub(r'\s+', ' ', doc.strip().split('\n\n')[0]).strip().replace('|', '\\|')
    return para if len(para) <= SUMMARY_CHARS else para[:SUMMARY_CHARS - 1].rstrip() + '…'


def first_sentence(doc):
    """The module docstring's first sentence, at most 100 characters, as a section label."""
    first = re.sub(r'\s+', ' ', doc.strip().split('\n\n')[0]) if doc else ''
    first = re.split(r'(?<=[.!?])\s', first, maxsplit=1)[0] if first else ''
    return first if len(first) <= 100 else first[:99].rstrip() + '…'


def signature(fn, drop_self=False):
    """'name(a, b=, *args, **kw)': defaults shown as a bare '=' to keep rows short."""
    a = fn.args
    positional = a.posonlyargs + a.args
    parts = []
    for i, arg in enumerate(positional):
        if drop_self and i == 0 and arg.arg in ('self', 'cls'):
            continue
        parts.append(arg.arg + ('=' if i >= len(positional) - len(a.defaults) else ''))
    if a.vararg:
        parts.append('*' + a.vararg.arg)
    for arg, default in zip(a.kwonlyargs, a.kw_defaults):
        parts.append(arg.arg + ('=' if default is not None else ''))
    if a.kwarg:
        parts.append('**' + a.kwarg.arg)
    return f"{fn.name}({', '.join(parts)})"


def module_rows(path):
    """(module docstring, [(signature, summary)]) for one file's public functions, classes and their public methods."""
    tree = ast.parse(open(path, encoding='utf-8').read())
    rows = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith('_'):
            rows.append((signature(node), first_paragraph(ast.get_docstring(node))))
        elif isinstance(node, ast.ClassDef) and not node.name.startswith('_'):
            rows.append((f"class {node.name}", first_paragraph(ast.get_docstring(node))))
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and not item.name.startswith('_'):
                    rows.append((f"{node.name}.{signature(item, drop_self=True)}", first_paragraph(ast.get_docstring(item))))
    return ast.get_docstring(tree) or '', rows


def render():
    """The whole KIT-REGISTRY.md text."""
    out = ["# Kit Registry: chuang-platform-kit", "",
           "**Generated by `python scripts/build-kit-registry.py` from the docstrings: do not edit by hand; edit the",
           "docstring and regenerate.** `tests/test-kit-registry.py` fails when this file is stale or a public name has no",
           "docstring.", "",
           "**Kit first:** before writing anything a second project could use (a retry, a REST client, a webhook's",
           "check, a once-only claim, a sender), read this file. If the kit has it, import it; if it is close, change the",
           "kit (a kit commit, a tag, the pin bump in each host). A host's own registry lists only its own code.", ""]
    for path in sorted(glob.glob(os.path.join(PKG, '*.py'))):
        base = os.path.basename(path)
        if base == '__init__.py':
            continue
        doc, rows = module_rows(path)
        label = first_sentence(doc)
        out.append(f"## `{base[:-3]}`" + (f": {label}" if label else ''))
        out.append('')
        if rows:
            out += ['| Name | Purpose |', '|---|---|'] + [f"| `{sig}` | {summary} |" for sig, summary in rows]
        else:
            out.append('_No public names._')
        out.append('')
    return '\n'.join(out) + '\n'


def main(argv):
    """Write, check or print the registry; 1 when --check finds it stale."""
    text = render()
    if '--stdout' in argv:
        sys.stdout.write(text)
        return 0
    if '--check' in argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != text:
            print("KIT-REGISTRY.md is stale: run `python scripts/build-kit-registry.py`", file=sys.stderr)
            return 1
        print("KIT-REGISTRY.md is current")
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print(f"wrote KIT-REGISTRY.md: {text.count(chr(10) + '| `')} rows, {len(text)} chars (~{len(text) // 4} tokens)")
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
